use super::*;
use pioneer_optical::envelope::{signature::SigningKey, Update};

fn archive(update: &Update, normal_only: bool) -> Vec<u8> {
    let mut tar = tar::Builder::new(Vec::new());
    for (name, bytes) in [
        ("kernel.enc", update.kernel_transfer()),
        ("normal.enc", update.normal_transfer()),
    ] {
        if normal_only && name == "kernel.enc" {
            continue;
        }
        let mut header = tar::Header::new_gnu();
        header.set_size(bytes.len() as u64);
        header.set_mode(0o644);
        header.set_cksum();
        tar.append_data(&mut header, name, bytes).unwrap();
    }
    tar.into_inner().unwrap()
}
fn startup(update: Update, value: u16, foreign: bool) -> Update {
    let mut normal = update.normal().image.clone();
    normal[0x600..0x614].copy_from_slice(&[
        0x79, 0, 0, 0x9f, 0x5e, 0x41, 0x10, 0, 0x79, 0x20, 0xfe, 0x24, 0x47, 6, 0xf8, 1, 0x5e,
        0x41, 7, 0x80,
    ]);
    normal[0x60a..0x60c].copy_from_slice(&value.to_be_bytes());
    normal[0x780..0x786].copy_from_slice(&[0x5e, 0x40, 0x0a, 0x1a, 0x54, 0x70]);
    if foreign {
        normal[0x701] = 0x13;
    }
    normal[16..20].fill(0);
    let sum = normal.as_chunks::<4>().0.iter().fold(0u32, |sum, word| {
        sum.wrapping_add(u32::from_be_bytes(*word))
    });
    normal[16..20].copy_from_slice(&sum.wrapping_neg().to_be_bytes());
    let mut bytes = update.normal().repack(&normal).unwrap();
    let mut key = [0; 20];
    key[19] = 5;
    SigningKey::from_bytes(key)
        .unwrap()
        .sign_normal(&mut bytes)
        .unwrap();
    Update::load(update.kernel_transfer(), &bytes).unwrap()
}

/// The website crossflash graph is generated by [`crate::crossflash::classified_routes`],
/// which must evaluate every admitted pair through the SAME [`crate::crossflash::decide`]
/// the live flasher and `freemkv-crossflash --why` use. This guards the invariant that
/// "how Flash flashes == how --why explains == how the website shows": the batch graph
/// can never deviate from a per-pair flasher decision.
#[test]
fn website_graph_matches_the_flasher_decision_for_every_pair() {
    let plain = prepared_tests::pair(false, 1);
    let old = prepared_tests::pair(false, 0);
    let barrier = prepared_tests::pair(true, 1);
    let source = startup(plain.clone(), 0xff01, false);
    let target = startup(old.clone(), 0xfe24, false);
    let foreign = startup(old.clone(), 0xfe24, true);
    let packages_owned = [
        archive(&plain, false),
        archive(&old, false),
        archive(&barrier, false),
        archive(&source, false),
        archive(&target, false),
        archive(&foreign, false),
        archive(&target, true), // Normal-only (pair-local decode)
        b"invalid package".to_vec(),
    ];
    let packages: Vec<&[u8]> = packages_owned.iter().map(Vec::as_slice).collect();
    let routes =
        crate::crossflash::classified_routes(crate::backend::registry::PIONEER_PLATFORM, &packages);
    let mut expected = Vec::new();
    for i in 0..packages.len() {
        for j in 0..packages.len() {
            if i == j {
                continue;
            }
            let decision = crate::crossflash::decide(
                crate::backend::registry::PIONEER_PLATFORM,
                packages[i],
                packages[j],
            );
            expected.extend(decision.routes.into_iter().map(|route| (i, j, route)));
        }
    }
    assert_eq!(routes, expected);
}

/// Timing witness for the whole-catalogue crossflash scan (the website graph).
/// Not a gate — run with `--ignored --nocapture` to record ms/pair. Each pair
/// decodes two packages and runs the full `decide` prepare pipeline, the exact
/// work the Arc-shared `Receiver` optimisation targets. Was ~1s/pair when the
/// per-pair `Receiver::clone()` copied ~1.9MB of Envelope.
#[test]
#[ignore]
fn crossflash_scan_timing() {
    let mut owned: Vec<Vec<u8>> = Vec::new();
    for marker in 0u8..20 {
        let p = prepared_tests::pair(marker % 2 == 0, marker);
        owned.push(archive(&p, false));
        owned.push(archive(
            &startup(p.clone(), 0xfe00 + marker as u16, marker % 3 == 0),
            false,
        ));
    }
    let packages: Vec<&[u8]> = owned.iter().map(Vec::as_slice).collect();
    let pairs = packages.len() * (packages.len() - 1);
    let start = std::time::Instant::now();
    let routes =
        crate::crossflash::classified_routes(crate::backend::registry::PIONEER_PLATFORM, &packages);
    let elapsed = start.elapsed();
    eprintln!(
        "crossflash scan: {} packages, {} directed pairs, {} routes in {:?} => {:.3} ms/pair",
        packages.len(),
        pairs,
        routes.len(),
        elapsed,
        elapsed.as_secs_f64() * 1000.0 / pairs as f64,
    );
}
